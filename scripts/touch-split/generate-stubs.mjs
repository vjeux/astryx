// Writes packages/core/src/touch-stubs/<path>.ts for every touch module a
// component imports through `#touch/<path>`: the same export names, each a
// no-op, so a build under the astryx-desktop condition resolves the touch
// layer to nothing. Types come from the real module.
import {build} from 'esbuild';
import {mkdirSync, readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {dirname, join, relative, resolve} from 'node:path';

const root = resolve(process.argv[2] ?? '.');
const src = join(root, 'packages/core/src');
const check = process.argv.includes('--check');

function sources(dir) {
  return readdirSync(dir, {withFileTypes: true}).flatMap(entry => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      return entry.name === 'touch-stubs' || entry.name === 'node_modules' ? [] : sources(path);
    }
    return /\.tsx?$/.test(entry.name) ? [path] : [];
  });
}

const specifiers = new Set();
for (const file of sources(src)) {
  for (const m of readFileSync(file, 'utf8').matchAll(/from '#touch\/([^']+)'/g)) {
    specifiers.add(m[1]);
  }
}
let stale = 0;
for (const specifier of [...specifiers].sort()) {
  const real = join(src, `${specifier}.ts`);
  const result = await build({entryPoints: [real], bundle: false, write: false, metafile: true, format: 'esm', logLevel: 'silent'});
  const names = Object.values(result.metafile.outputs)[0].exports.sort();
  const stub = join(src, 'touch-stubs', `${specifier}.ts`);
  const fromStub = relative(dirname(stub), real).replace(/\.ts$/, '');
  const text = [
    '// Copyright (c) Meta Platforms, Inc. and affiliates.',
    '// Generated by scripts/touch-split/generate-stubs.mjs; do not edit.',
    '',
    `/** The exports of ${specifier}.ts as no-ops, for the astryx-desktop condition. */`,
    '',
    `import type * as Touch from '${fromStub}';`,
    '',
    '// Reached only behind the touch presentation: on a desktop build a pointer',
    '// that turns coarse later keeps the desktop behavior.',
    'const noop = (): undefined => undefined;',
    ...names.map(name => `export const ${name} = noop as unknown as typeof Touch.${name};`),
    '',
  ].join('\n');
  if (check) {
    let current = '';
    try { current = readFileSync(stub, 'utf8'); } catch {}
    if (current !== text) { console.error(`stale: ${relative(root, stub)}`); stale++; }
  } else {
    mkdirSync(dirname(stub), {recursive: true});
    writeFileSync(stub, text);
    console.log(`${relative(root, stub)}: ${names.join(', ')}`);
  }
}
if (stale > 0) process.exit(1);
